export const getGreekPage = (path) => greekPages.find((p) => p.path === path);

/** Greek counterpart of an English page, for hreflang; undefined when there is none. */
export const greekPathFor = (enPath) => greekPages.find((p) => p.enPath === enPath)?.path;

/** hreflang map shared by both pages of a pair. */
export const languagesFor = (enPath) => {
  const el = greekPathFor(enPath);
  return el ? { en: enPath, el, 'x-default': enPath } : undefined;
};
